def _dedupe(items) -> list[tuple[str, list[str]]]:
    seen: set[str] = set()
    res: list[tuple[str, list[str]]] = []
    for q, o in items:
        if q not in seen and len(o) == 4 and len(set(o)) == 4:
            seen.add(q)
            res.append((q, o))
    return res


