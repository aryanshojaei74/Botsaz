        from config import Session
        from models import Setting
        async with Session() as s:
            row = await s.scalar(_sel(Setting).where(Setting.bot_id == int(bot_id), Setting.key == f"quiz_used:{chat_id}"))
        d = _j.loads(row.value) if row and row.value else {}
