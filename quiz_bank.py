def qid(q: str) -> str:
    """شناسهٔ پایدار یک سؤال (برای ذخیرهٔ «قبلاً پرسیده‌شده»ها در دیتابیس؛ با تغییر ترتیب بانک بی‌اثر می‌ماند)."""
    import zlib
    return f"{zlib.crc32(q.encode('utf-8')) & 0xFFFFFFFF:08x}"


def make_quiz(rnd=secrets, scope: tuple = (0, 0), cat: str | None = None, used: dict | None = None) -> dict:
    """{q, opts[۴ گزینهٔ بُرخورده], a: شمارهٔ گزینهٔ درست, right, cat, id}
    cat: یکی از CATS یا None (= همهٔ موضوع‌ها). used: {cat: [id,…]} — سؤال‌های قبلاً پرسیده‌شده در همین گروه؛ سؤال تکراری
    نمی‌آید تا وقتی همهٔ سؤال‌های آن موضوع پرسیده شود (آن‌وقت فهرست آن موضوع صفر می‌شود). used درجا به‌روز می‌شود.
    بدون used: فقط حافظهٔ پروسه (_RECENT)."""
    key = cat if cat in POOLS else "all"
    pool = POOLS[cat] if cat in POOLS else QUIZ_ALL
    if used is not None:
        seen = set(used.get(key, []))
        cand = [i for i, (q, _o) in enumerate(pool) if qid(q) not in seen]
        if not cand:                                   # همه پرسیده شد ⇒ دور تازه
            used[key] = []
            cand = list(range(len(pool)))
    else:
        recent = _RECENT.setdefault((scope, key), [])
        cand = [i for i in range(len(pool)) if i not in recent]
        if not cand:
            recent.clear()
            cand = list(range(len(pool)))
    weighted = []
    for i in cand:
        weighted.append(i)
        if cat is None and pool[i][0] in _BIO_CHEM_Q:
            weighted.append(i)
    idx = weighted[rnd.randbelow(len(weighted))]
    q, opts = pool[idx]
    if used is not None:
        used.setdefault(key, []).append(qid(q))
        if len(used[key]) > 3000:
            del used[key][:len(used[key]) - 3000]
    else:
        _RECENT[(scope, key)].append(idx)
    right = opts[0]
    shuffled = list(opts)
    for i in range(len(shuffled) - 1, 0, -1):
        j = rnd.randbelow(i + 1)
        shuffled[i], shuffled[j] = shuffled[j], shuffled[i]
    return {"q": q, "opts": shuffled, "a": str(shuffled.index(right) + 1), "right": right, "cat": cat or "", "id": qid(q)}


