def make_quiz(rnd=secrets, scope: tuple = (0, 0)) -> dict:
    """{q: سؤال، opts: [۴ گزینهٔ بُرخورده]، a: شمارهٔ گزینهٔ درست (۱..۴ به‌صورت رشته)، right}
    scope=(bot_id, chat_id): در همان گروه، تا ۸۰٪ بانک سؤال تکراری نمی‌آید (حافظهٔ پردازش)."""
    pool = QUIZ_ALL
    recent = _RECENT.setdefault(scope, [])
    keep = max(1, int(len(pool) * 0.8))
    cand = [i for i in range(len(pool)) if i not in recent]
    # زیست/شیمی دو برابر شانس
    weighted = []
    for i in cand:
        weighted.append(i)
        if pool[i][0] in _BIO_CHEM_Q:
            weighted.append(i)
    idx = weighted[rnd.randbelow(len(weighted))] if weighted else rnd.randbelow(len(pool))
    recent.append(idx)
    if len(recent) > keep:
        del recent[0:len(recent) - keep]
    q, opts = pool[idx]
    right = opts[0]
    shuffled = list(opts)
    for i in range(len(shuffled) - 1, 0, -1):
        j = rnd.randbelow(i + 1)
        shuffled[i], shuffled[j] = shuffled[j], shuffled[i]
    return {"q": q, "opts": shuffled, "a": str(shuffled.index(right) + 1), "right": right}


def make_emoji(rnd=secrets) -> dict:
    """{q: ایموجی‌ها (۲ تا ۵ تا)، w: پاسخ نمایشی، accept: [همهٔ پاسخ‌های پذیرفته]}"""
    q, answers = EMOJI[rnd.randbelow(len(EMOJI))]
    return {"q": q, "w": answers[0], "accept": list(answers)}
