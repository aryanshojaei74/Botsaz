def expand_query(q: str) -> str:
    """پرسش را با مترادف‌ها غنی می‌کند تا جست‌وجوی محلی بهتر بخورد."""
    out = [q]
    low = (q or "").replace("\u200c", "").lower()
    for k, v in SYNONYMS.items():
        if k.replace("\u200c", "") in low:
            out.append(v)
    return " ".join(out)


def full_text() -> str:
    """متنِ کاملِ دفترچه — برایِ مینی‌اپ و برایِ خوراکِ دستیار."""
    out = ["# راهنمای کامل بات‌ساز\n"]
    out.append("## بخش‌های پنل مدیریت\n")
    for sec in SECTIONS.values():
        out.append(f"### {sec['title']}")
        for name, desc in sec["items"]:
            out.append(f"- **{name}** — {desc}")
        out.append("")
    out.append("## کارهای پرتکرار\n")
    for q, a in HOWTO:
        out.append(f"### {q}\n{a}\n")
    out.append("## پرسش‌های پرتکرار\n")
    for q, a in FAQ:
        out.append(f"**{q}**\n{a}\n")
    return "\n".join(out)


def compact_for_prompt() -> str:
    """نسخهٔ فشرده برایِ system prompt دستیار (کم‌حجم‌تر)."""
    parts = []
    for sec in SECTIONS.values():
        items = " · ".join(n for n, _ in sec["items"])
        parts.append(f"{sec['title']}: {items}")
    parts.append("")
    for q, a in HOWTO:
        parts.append(f"{q} => {a}")
    for q, a in FAQ:
        parts.append(f"{q} => {a}")
    return "\n".join(parts)
