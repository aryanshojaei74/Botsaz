async def get_text(bot_id: int, key: str) -> str:
    """متنِ تنظیم‌شده یا پیش‌فرض."""
    _, default = TEXTS.get(key, ("", ""))
    try:
        from tenant import get_setting
        v = (await get_setting(bot_id, f"smm_txt_{key}", "") or "").strip()
        return v or default
    except Exception:
        return default


async def get_custom(bot_id: int, key: str) -> str:
    """متنِ دلخواهِ ادمین، یا "" اگر تنظیم نکرده (برخلافِ get_text که پیش‌فرض را هم برمی‌گرداند)."""
    try:
        from tenant import get_setting
        return (await get_setting(bot_id, f"smm_txt_{key}", "") or "").strip()
    except Exception:
        return ""
